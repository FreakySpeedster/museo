export type ErrorCode =
  | "BAD_REQUEST"
  | "UNAUTHORIZED"
  | "FORBIDDEN"
  | "NOT_FOUND"
  | "CONFLICT"
  | "SHELF_LIMIT"
  | "PAYWALL"
  | "RATE_LIMITED"
  | "UPLOAD_INVALID"
  | "UNPROCESSABLE";

const STATUS: Record<ErrorCode, number> = {
  BAD_REQUEST: 400,
  UNAUTHORIZED: 401,
  FORBIDDEN: 403,
  NOT_FOUND: 404,
  CONFLICT: 409,
  SHELF_LIMIT: 422,
  PAYWALL: 402,
  RATE_LIMITED: 429,
  UPLOAD_INVALID: 400,
  UNPROCESSABLE: 422,
};

export class AppError extends Error {
  readonly code: ErrorCode;
  readonly status: number;
  readonly details?: unknown;
  constructor(code: ErrorCode, message: string, details?: unknown) {
    super(message);
    this.name = "AppError";
    this.code = code;
    this.status = STATUS[code];
    this.details = details;
  }
}
